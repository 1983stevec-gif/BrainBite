def make_tree(collection, asset_id, root, name, x, y, z, scale):
    trunk = make_material("BB_Jungle_Trunk", (0.25, 0.11, 0.045, 1.0), roughness=0.9)
    leaf_dark = make_material("BB_Jungle_Leaf_Dark", (0.025, 0.26, 0.12, 1.0), roughness=0.86)
    leaf = make_material("BB_Jungle_Leaf", (0.06, 0.55, 0.20, 1.0), roughness=0.82)
    leaf_light = make_material("BB_Jungle_Leaf_Light", (0.25, 0.78, 0.26, 1.0), roughness=0.78)
    add_cylinder(collection, asset_id, root, f"{name}_Trunk", (x, y, z + 0.85 * scale), 0.22 * scale, 1.7 * scale, trunk, vertices=10, kind="tree_trunk")
    for index, (dx, dy, dz, s, material) in enumerate(
        [
            (-0.35, 0.0, 1.70, 0.75, leaf_dark),
            (0.30, -0.05, 1.88, 0.72, leaf),
            (0.0, 0.08, 2.20, 0.64, leaf_light),
            (0.44, 0.12, 2.22, 0.44, leaf),
            (-0.44, -0.04, 2.04, 0.45, leaf_light),
        ],
        start=1,
    ):
        add_ico_sphere(collection, asset_id, root, f"{name}_Canopy_{index:02d}", (x + dx * scale, y + dy * scale, z + dz * scale), (s * scale, s * 0.82 * scale, s * 0.78 * scale), material, subdivisions=1, kind="tree_canopy")


