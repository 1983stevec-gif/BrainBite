def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def parse_cli() -> argparse.Namespace:
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=repo_root() / "assets" / "generated" / "blender",
        help="Generated asset root; defaults to assets/generated/blender.",
    )
    parser.add_argument(
        "--verify-only",
        action="store_true",
        help="Import the existing manifest GLBs in Blender without rebuilding.",
    )
    parser.add_argument(
        "--skip-verify",
        action="store_true",
        help="Build and export without the Blender-side GLB import check.",
    )
    return parser.parse_args(argv)


def set_node_input(node, name, value) -> None:
    socket = node.inputs.get(name)
    if socket is not None:
        socket.default_value = value


def make_material(
    name: str,
    color: tuple[float, float, float, float],
    *,
    roughness: float = 0.72,
    metallic: float = 0.0,
    emission: tuple[float, float, float, float] | None = None,
    emission_strength: float = 0.0,
) -> bpy.types.Material:
    if name in MATERIALS:
        return MATERIALS[name]
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    material.diffuse_color = color
    material["brainbite_generated"] = True
    material["brainbite_build_id"] = BUILD_ID
    material["brainbite_license"] = LICENSE_NOTE
    nodes = material.node_tree.nodes
    principled = nodes.get("Principled BSDF")
    if principled is not None:
        set_node_input(principled, "Base Color", color)
        set_node_input(principled, "Roughness", roughness)
        set_node_input(principled, "Metallic", metallic)
        if emission is not None:
            set_node_input(principled, "Emission Color", emission)
            set_node_input(principled, "Emission Strength", emission_strength)
    MATERIALS[name] = material
    return material


def link_to_collection(obj: bpy.types.Object, collection: bpy.types.Collection) -> None:
    for current in list(obj.users_collection):
        current.objects.unlink(obj)
    collection.objects.link(obj)


def tag_object(
    obj: bpy.types.Object,
    asset_id: str,
    kind: str,
    root: bpy.types.Object,
    **extra,
) -> bpy.types.Object:
    obj["brainbite_generated"] = True
    obj["brainbite_asset_id"] = asset_id
    obj["brainbite_asset_root"] = root.name
    obj["brainbite_kind"] = kind
    obj["brainbite_build_id"] = BUILD_ID
    obj["brainbite_pipeline_version"] = PIPELINE_VERSION
    obj["brainbite_license"] = LICENSE_NOTE
    for key, value in extra.items():
        obj[key] = value
    return obj


def parent_keep_world(obj: bpy.types.Object, root: bpy.types.Object) -> None:
    matrix = obj.matrix_world.copy()
    obj.parent = root
    obj.matrix_world = matrix


def finish_object(
    obj: bpy.types.Object,
    collection: bpy.types.Collection,
    asset_id: str,
    kind: str,
    root: bpy.types.Object,
    *,
    material: bpy.types.Material | None = None,
    smooth: bool = False,
    **extra,
) -> bpy.types.Object:
    link_to_collection(obj, collection)
    if material is not None and obj.type == "MESH":
        obj.data.materials.append(material)
    if smooth and obj.type == "MESH":
        for polygon in obj.data.polygons:
            polygon.use_smooth = True
    parent_keep_world(obj, root)
    return tag_object(obj, asset_id, kind, root, **extra)


def add_empty(
    collection: bpy.types.Collection,
    root: bpy.types.Object,
    asset_id: str,
    name: str,
    kind: str,
    *,
    display_size: float = 0.25,
    **extra,
) -> bpy.types.Object:
    obj = bpy.data.objects.new(name, None)
    collection.objects.link(obj)
    obj.empty_display_type = "PLAIN_AXES"
    obj.empty_display_size = display_size
    parent_keep_world(obj, root)
    return tag_object(obj, asset_id, kind, root, **extra)


def add_cube(
    collection,
    asset_id,
    root,
    name,
    location,
    dimensions,
    material,
    *,
    bevel: float = 0.0,
    rotation=(0.0, 0.0, 0.0),
    kind="prop",
    **extra,
):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=location, rotation=rotation)
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if bevel:
        modifier = obj.modifiers.new("Soft bevel", "BEVEL")
        modifier.width = bevel
        modifier.segments = 2
        modifier.limit_method = "ANGLE"
    return finish_object(obj, collection, asset_id, kind, root, material=material, **extra)


