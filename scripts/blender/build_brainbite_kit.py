def add_text(
    collection,
    asset_id,
    root,
    name,
    body,
    location,
    size,
    material,
    *,
    rotation=(math.radians(90.0), 0.0, 0.0),
    kind="label",
    **extra,
):
    bpy.ops.object.text_add(location=location, rotation=rotation)
    obj = bpy.context.object
    obj.name = name
    obj.data.body = body
    obj.data.align_x = "CENTER"
    obj.data.align_y = "CENTER"
    obj.data.size = size
    obj.data.extrude = 0.025
    obj.data.bevel_depth = 0.008
    bpy.ops.object.convert(target="MESH")
    return finish_object(obj, collection, asset_id, kind, root, material=material, **extra)


def add_segment(
    collection,
    asset_id,
    root,
    name,
    start,
    end,
    radius,
    material,
    *,
    kind="tentacle",
    **extra,
):
    start_vec = Vector(start)
    end_vec = Vector(end)
    delta = end_vec - start_vec
    midpoint = (start_vec + end_vec) * 0.5
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=12,
        radius=radius,
        depth=delta.length,
        location=midpoint,
    )
    obj = bpy.context.object
    obj.name = name
    obj.rotation_mode = "QUATERNION"
    obj.rotation_quaternion = delta.to_track_quat("Z", "Y")
    return finish_object(
        obj,
        collection,
        asset_id,
        kind,
        root,
        material=material,
        smooth=True,
        **extra,
    )


def new_asset(asset_id: str, display_name: str, description: str):
    scene = bpy.context.scene
    collection = bpy.data.collections.new(f"BB_{asset_id}")
    scene.collection.children.link(collection)
    root = bpy.data.objects.new(f"BrainBite_{asset_id}_ROOT", None)
    collection.objects.link(root)
    root.empty_display_type = "CUBE"
    root.empty_display_size = 0.35
    tag_object(root, asset_id, "asset_root", root, display_name=display_name)
    root["brainbite_description"] = description
    root["brainbite_style"] = STYLE_NOTE
    root["brainbite_source_script"] = SOURCE_SCRIPT
    root["brainbite_deterministic_seed"] = DETERMINISTIC_SEED
    root["brainbite_provenance_json"] = json.dumps(
        {
            "asset_id": asset_id,
            "build_id": BUILD_ID,
            "license": LICENSE_NOTE,
            "pipeline_version": PIPELINE_VERSION,
            "source_script": SOURCE_SCRIPT,
            "style": STYLE_NOTE,
        },
        sort_keys=True,
    )
    spec = {
        "asset_id": asset_id,
        "display_name": display_name,
        "description": description,
        "collection": collection,
        "root": root,
    }
    ASSETS.append(spec)
    return collection, root


