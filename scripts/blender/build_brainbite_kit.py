def reset_scene() -> None:
    random.seed(DETERMINISTIC_SEED)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.length_unit = "METERS"
    # Blender 5.2.1 exposes the current Eevee engine under this stable ID.
    scene.render.engine = "BLENDER_EEVEE"
    scene["brainbite_build_id"] = BUILD_ID
    scene["brainbite_pipeline_version"] = PIPELINE_VERSION
    scene["brainbite_deterministic_seed"] = DETERMINISTIC_SEED
    scene["brainbite_source_script"] = SOURCE_SCRIPT
    scene["brainbite_license"] = LICENSE_NOTE
    scene["brainbite_style"] = STYLE_NOTE


def call_supported(operator, kwargs):
    properties = operator.get_rna_type().properties.keys()
    return operator(**{key: value for key, value in kwargs.items() if key in properties})


def select_asset(spec) -> None:
    bpy.ops.object.select_all(action="DESELECT")
    for obj in spec["collection"].objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = spec["root"]


def export_asset(spec, output_path: Path) -> dict:
    select_asset(spec)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    call_supported(
        bpy.ops.export_scene.gltf,
        {
            "filepath": str(output_path),
            "export_format": "GLB",
            "use_selection": True,
            "export_apply": True,
            "export_materials": "EXPORT",
            "export_animations": True,
            "export_animation_mode": "ACTIONS",
            "export_cameras": False,
            "export_lights": False,
            "export_extras": True,
        },
    )
    if not output_path.is_file() or output_path.stat().st_size < 32:
        raise RuntimeError(f"Blender did not produce a usable GLB: {output_path}")
    with output_path.open("rb") as handle:
        header = handle.read(12)
    if header[:4] != b"glTF" or struct.unpack("<I", header[4:8])[0] != 2:
        raise RuntimeError(f"Invalid GLB header: {output_path}")
    objects = list(spec["collection"].objects)
    mesh_count = sum(obj.type == "MESH" for obj in objects)
    material_names = sorted(
        {
            material.name
            for obj in objects
            if obj.type == "MESH"
            for material in obj.data.materials
            if material is not None
        }
    )
    return {
        "asset_id": spec["asset_id"],
        "display_name": spec["display_name"],
        "description": spec["description"],
        "file": output_path.name,
        "root_object": spec["root"].name,
        "object_count": len(objects),
        "mesh_count": mesh_count,
        "material_names": material_names,
        "size_bytes": output_path.stat().st_size,
        "sha256": hashlib.sha256(output_path.read_bytes()).hexdigest(),
    }


def import_verify(path: Path) -> dict:
    if not path.is_file():
        raise RuntimeError(f"Missing GLB: {path}")
    raw = path.read_bytes()
    if len(raw) < 20 or raw[:4] != b"glTF" or struct.unpack("<I", raw[4:8])[0] != 2:
        raise RuntimeError(f"Invalid GLB header: {path}")
    reset_scene()
    if not hasattr(bpy.ops.import_scene, "gltf"):
        raise RuntimeError("Blender glTF importer is unavailable")
    call_supported(bpy.ops.import_scene.gltf, {"filepath": str(path)})
    imported = list(bpy.context.scene.objects)
    mesh_count = sum(obj.type == "MESH" for obj in imported)
    if mesh_count < 1:
        raise RuntimeError(f"GLB imported without mesh geometry: {path}")
    return {
        "file": path.name,
        "header": "glTF v2",
        "imported_object_count": len(imported),
        "imported_mesh_count": mesh_count,
    }


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def build(output_root: Path, skip_verify: bool) -> None:
    output_root = output_root.resolve()
    source_dir = output_root / "source"
    glb_dir = output_root / "glb"
    source_dir.mkdir(parents=True, exist_ok=True)
    glb_dir.mkdir(parents=True, exist_ok=True)
    reset_scene()
    ASSETS.clear()
    MATERIALS.clear()
    build_mascot()
    build_jungle_props()
    build_portal()
    build_answer_pillars()
    build_kraken()
    add_preview_collection()
    source_blend = source_dir / "brainbite_starter_kit.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(source_blend))
    output_records = []
    for spec in ASSETS:
        output_records.append(export_asset(spec, glb_dir / ASSET_FILES[spec["asset_id"]]))
    manifest = {
        "schema": "brainbite.blender.asset-manifest.v1",
        "build_id": BUILD_ID,
        "pipeline_version": PIPELINE_VERSION,
        "blender_version": bpy.app.version_string,
        "deterministic_seed": DETERMINISTIC_SEED,
        "source_script": SOURCE_SCRIPT,
        "source_blend": "assets/generated/blender/source/brainbite_starter_kit.blend",
        "supporting_source_scripts": ["scripts/blender/mascot_v2.py"],
        "output_directory": "assets/generated/blender/glb",
        "license": LICENSE_NOTE,
        "style": STYLE_NOTE,
        "assets": output_records,
    }
    manifest_path = output_root / "manifest.json"
    if not skip_verify:
        manifest["verification"] = {
            "method": "Blender 5.2 headless glTF import",
            "status": "passed",
            "files": [import_verify(glb_dir / record["file"]) for record in output_records],
        }
    else:
        manifest["verification"] = {"method": "skipped by --skip-verify", "status": "skipped"}
    write_json(manifest_path, manifest)
    print(f"BUILD PASS {BUILD_ID}")
    print(f"SOURCE {source_blend}")
    for record in output_records:
        print(f"GLB {record['file']} {record['size_bytes']} bytes sha256={record['sha256']}")
    print(f"MANIFEST {manifest_path}")
    print(f"VERIFY {manifest['verification']['status']}")


def verify_existing(output_root: Path) -> None:
    manifest_path = output_root.resolve() / "manifest.json"
    if not manifest_path.is_file():
        raise RuntimeError(f"Missing manifest: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    glb_dir = output_root.resolve() / "glb"
    results = []
    for asset in manifest.get("assets", []):
        path = glb_dir / asset["file"]
        result = import_verify(path)
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != asset.get("sha256"):
            raise RuntimeError(f"SHA-256 mismatch for {path.name}")
        results.append(result)
    if len(results) != len(ASSET_FILES):
        raise RuntimeError(f"Expected {len(ASSET_FILES)} manifest assets, found {len(results)}")
    print(f"VERIFY PASS {manifest['build_id']}")
    for result in results:
        print(f"IMPORT PASS {result['file']} objects={result['imported_object_count']} meshes={result['imported_mesh_count']}")


def main() -> None:
    args = parse_cli()
    try:
        if args.verify_only:
            verify_existing(args.output)
        else:
            build(args.output, args.skip_verify)
    except Exception as exc:
        print(f"BUILD FAIL {type(exc).__name__}: {exc}", file=sys.stderr)
        raise


if __name__ == "__main__":
    main()
