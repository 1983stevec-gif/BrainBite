import { writeFileSync, readdirSync, readFileSync, rmSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Fredoka:wght@450;550;650;700&family=Nunito:wght@600;700;800;900&display=swap';
const CHROME_UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': CHROME_UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];

// One variable file per family covers every requested weight, so collect the weight
// range and a single source per family instead of one duplicate file per weight.
const families = new Map();
for (const [, subset, block] of blocks) {
  if (subset !== 'latin') continue;
  const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
  const weight = Number(/font-weight:\s*(\d+)/.exec(block)?.[1]);
  const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
  if (!family || !weight || !url || !range) continue;
  const entry = families.get(family) || { min: weight, max: weight, url, range, hash: null };
  entry.min = Math.min(entry.min, weight);
  entry.max = Math.max(entry.max, weight);
  families.set(family, entry);
}

rmSync('assets/fonts', { recursive: true, force: true });
mkdirSync('assets/fonts', { recursive: true });

const faces = [];
const hashes = [];
for (const [family, entry] of families) {
  const file = `${family.toLowerCase()}-variable.woff2`;
  const bytes = new Uint8Array(await (await fetch(entry.url)).arrayBuffer());
  writeFileSync(`assets/fonts/${file}`, bytes);
  const hash = createHash('sha256').update(bytes).digest('hex');
  hashes.push(`/* sha256:${hash} assets/fonts/${file} */`);
  faces.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${entry.min} ${entry.max};font-display:swap;src:url('assets/fonts/${file}') format('woff2');unicode-range:${entry.range}}`);
  console.log(`saved assets/fonts/${file} (${bytes.length} bytes, sha256:${hash.slice(0, 16)}, weights ${entry.min}-${entry.max})`);
}

writeFileSync('fonts.css', [
  '/* Self-hosted production fonts. Generated by scripts/self-host-fonts.mjs - do not edit by hand. */',
  '/* Verify integrity with: npm run check:precache */',
  ...hashes,
  ...faces,
  '',
].join('\n'));
const files = readdirSync('assets/fonts');
const total = files.reduce((sum, file) => sum + readFileSync(`assets/fonts/${file}`).length, 0);
console.log(`\nfonts.css written with ${faces.length} @font-face rules; ${files.length} font files, ${total} bytes total`);
